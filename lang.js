function _bodNoeud(n, lang) {
  if (n.nodeType === 3) {
    const p = n.parentElement;
    if (!p || /^(SCRIPT|STYLE|NOSCRIPT)$/.test(p.tagName)) return;
    if (lang === 'en') {
      const v = n.nodeValue, en = TEXTES_EN[_bodNorm(v)];
      if (en === undefined || en === _bodNorm(v)) return;
      if (!_bodOrig.has(n)) _bodOrig.set(n, v);
      const m = v.match(/^(\s*)[\s\S]*?(\s*)$/);
      n.nodeValue = m[1] + en + m[2];
    } else if (_bodOrig.has(n)) { n.nodeValue = _bodOrig.get(n); _bodOrig.delete(n); }
  } else if (n.nodeType === 1) {
    _bodAttrs.forEach(a => {
      if (!n.hasAttribute(a)) return;
      const d = 'data-fr-' + a;
      if (lang === 'en') {
        const v = n.getAttribute(a), en = TEXTES_EN[_bodNorm(v)];
        if (en === undefined || en === v) return;
        if (!n.hasAttribute(d)) n.setAttribute(d, v);
        n.setAttribute(a, en);
      } else if (n.hasAttribute(d)) { n.setAttribute(a, n.getAttribute(d)); n.removeAttribute(d); }
    });
  }
}
